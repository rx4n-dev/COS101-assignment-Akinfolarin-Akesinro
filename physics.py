
# PHYSICS FORMULAS

# 1. Speed = Distance / Time
def speed(distance, time):
    return distance / time

# 2. Force = Mass × Acceleration
def force(mass, acceleration):
    return mass * acceleration

# 3. Density = Mass / Volume
def density(mass, volume):
    return mass / volume

# 4. Work Done = Force × Distance
def work_done(force, distance):
    return force * distance

# 5. Pressure = Force / Area
def pressure(force, area):
    return force / area


# Example usage
print("Speed:", speed(100, 5), "m/s")
print("Force:", force(10, 5), "N")
print("Density:", density(20, 4), "kg/m³")
print("Work Done:", work_done(10, 5), "J")
print("Pressure:", pressure(100, 2), "Pa")
